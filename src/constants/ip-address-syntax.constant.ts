/** Синтаксис адресов и хостов для проверки публичного адреса. */
export const IP_ADDRESS_SYNTAX = {
  /** IPv4 в десятичной записи с точками: четыре октета. */
  // Октет без ведущих нулей: `012` libcurl и inet_aton читают как ВОСЬМЕРИЧНОЕ
  // (10), а Number() — как десятичное (12). Такая форма — неразборная, то есть
  // запрещённая, а не «публичный 12.0.0.1» (внешний аудит 13.11.2026).
  ipv4Text: /^(0|[1-9]\d{0,2})\.(0|[1-9]\d{0,2})\.(0|[1-9]\d{0,2})\.(0|[1-9]\d{0,2})$/,
  /** Группа IPv6: от одной до четырёх шестнадцатеричных цифр. */
  ipv6Group: /^[0-9a-fA-F]{1,4}$/,
  /** В хосте цели этих символов не бывает; libcurl разобрал бы их как userinfo или путь. */
  forbiddenHostChars: /[/?#@\\\s]/,
  /** Порт после хоста: `:8080` (диапазон проверяется отдельно). */
  portSuffix: /^:(\d{1,5})$/,
  /** Порт отдельно: только десятичные цифры. */
  port: /^\d{1,5}$/,
  /**
   * Подсеть в настройках: ровно `адрес/префикс`, префикс — десятичные цифры.
   * `Number()` прочёл бы `''` как 0 (`10.0.0.0/` — «запретить всё»), `0x8` и
   * `8e0` как 8; лишний `/…` прежде отрезался молча (внешний аудит 14.11.2026).
   */
  subnet: /^([^/]*)\/(\d{1,3})$/,
  /** Зона IPv6 (`fe80::1%eth0`, `%25eth0` в URL): имя интерфейса или его номер. */
  ipv6Zone: /^[0-9A-Za-z._~-]{1,64}$/,
  /** RFC 6874: `%` перед зоной внутри скобок URL кодируется как `%25`. */
  ipv6ZoneUrlEncoding: /^25/,
  /** Схема URL с двоеточием (`https:`), RFC 3986. */
  urlScheme: /^[a-z][a-z0-9+.-]*:$/,
  /** IPv6 в скобках URL: `[::1]` → `::1`. */
  brackets: /^\[(.*)\]$/,
  /** Зона имени из настроек после приведения к ASCII: метки через точку. */
  nameSuffix: /^[a-z0-9_-]+(?:\.[a-z0-9_-]+)*$/,
} as const;
